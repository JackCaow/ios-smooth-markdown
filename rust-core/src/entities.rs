pub fn punctuation(c: char) -> bool {
    let n = c as u32;
    PUNCTUATION
        .binary_search_by(|(a, b)| {
            if n < *a {
                std::cmp::Ordering::Greater
            } else if n > *b {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
